#!/usr/bin/env python3
"""Local PostgreSQL 18 with Apple container; credentials stay in private files.

The user explicitly authorized generating local-only DB passwords. This tool
never prints them, uses password-file mounts, and never disables authentication.
"""
import argparse
import json
import os
import re
import secrets
import stat
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / '.local' / 'secrets'
NAME = 'sauna-postgres-local'
VOLUME = 'sauna-postgres18-data'
LABEL = 'studio.sauna.project'
OWNER = 'sauna-api-local-db'
IMAGE = 'docker.io/library/postgres:18@sha256:979bccfde35445db618c65107d27d08c6c21339d8dc3ad4c830c6633947be0e4'
FILES = {'admin': 'postgres-admin-password', 'app': 'postgres-app-password'}


def command(args, data=None):
    result = subprocess.run(args, input=data, text=True, capture_output=True)
    if result.returncode:
        raise RuntimeError('Local database command failed; no credential-bearing output is displayed')
    return result.stdout


def verify_directory():
    for path in (ROOT / '.local', DIRECTORY):
        if path.is_symlink():
            raise RuntimeError('Refusing symlinked credential directory')
        path.mkdir(mode=0o700, exist_ok=True)
        info = path.stat()
        if info.st_uid != os.getuid() or stat.S_IMODE(info.st_mode) != 0o700:
            raise RuntimeError('Credential directory must be owned by this user with mode 0700')
    if any(p.name not in FILES.values() for p in DIRECTORY.iterdir()):
        raise RuntimeError('Use a dedicated directory containing only the local DB password files')


def verify_file(path):
    info = path.lstat()
    if not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid() or stat.S_IMODE(info.st_mode) != 0o600:
        raise RuntimeError('Local DB password file must be regular, owned, and mode 0600')
    # These files are generated by setup; restrict SQL/pgpass material to that alphabet.
    value = path.read_text().removesuffix('\n')
    if not re.fullmatch(r'[A-Za-z0-9_-]{48}', value):
        raise RuntimeError('Invalid local generated password file')
    return value


def setup():
    for name in FILES.values():
        rel = str((DIRECTORY / name).relative_to(ROOT))
        result = subprocess.run(['git', 'check-ignore', '--quiet', rel], cwd=ROOT)
        tracked = command(['git', '-C', str(ROOT), 'ls-files', '--', rel])
        if result.returncode or tracked:
            raise RuntimeError('Credential files must be ignored and untracked before creation')
    verify_directory()
    for name in FILES.values():
        path = DIRECTORY / name
        if not path.exists():
            fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, 'w') as stream:
                stream.write(secrets.token_urlsafe(36) + '\n')
        verify_file(path)
    print('Local-only DB credentials ready (0700 directory / 0600 files); values not displayed')


def owned():
    items = json.loads(command(['container', 'inspect', NAME]))
    if len(items) != 1 or items[0]['configuration']['id'] != NAME or items[0]['configuration'].get('labels', {}).get(LABEL) != OWNER:
        raise RuntimeError('Refusing to operate on a foreign container')
    return items[0]


def start():
    verify_directory()
    for name in FILES.values():
        verify_file(DIRECTORY / name)
    result = subprocess.run(['container', 'volume', 'inspect', VOLUME], text=True, capture_output=True)
    if result.returncode:
        command(['container', 'volume', 'create', '--label', f'{LABEL}={OWNER}', '-s', '2G', VOLUME])
    else:
        volumes = json.loads(result.stdout)
        if len(volumes) != 1 or volumes[0].get('configuration', {}).get('name') != VOLUME or volumes[0].get('configuration', {}).get('labels', {}).get(LABEL) != OWNER:
            raise RuntimeError('Refusing to use an unowned existing volume')
    existing = subprocess.run(['container', 'inspect', NAME], text=True, capture_output=True)
    if existing.returncode == 0:
        item = owned()
        if item['status']['state'] == 'running':
            print('Owned local PostgreSQL is already running')
            return
        if item['status']['state'] != 'stopped':
            raise RuntimeError('Local PostgreSQL is not in a restartable state')
        command(['container', 'start', NAME])
        print('Owned local PostgreSQL restarted; volume and credentials retained')
        return
    command(['container', 'run', '--platform', 'linux/arm64', '--detach', '--name', NAME,
             '--label', f'{LABEL}={OWNER}', '--cpus', '2', '--memory', '512M',
             '--publish', '127.0.0.1:55432:5432', '--volume', f'{VOLUME}:/var/lib/postgresql',
             '--mount', f'type=bind,source={DIRECTORY},target=/run/sauna-secrets,readonly',
             '--env', 'POSTGRES_USER=sauna_admin', '--env', 'POSTGRES_DB=sauna_local',
             '--env', 'POSTGRES_PASSWORD_FILE=/run/sauna-secrets/postgres-admin-password',
             '--env', 'POSTGRES_HOST_AUTH_METHOD=scram-sha-256',
             '--env', 'POSTGRES_INITDB_ARGS=--auth-host=scram-sha-256 --auth-local=scram-sha-256', IMAGE])
    print('Local PostgreSQL started; published only at 127.0.0.1:55432')


def query(sql):
    owned()
    # Password is read inside the VM into a private pgpass file, never argv/env.
    shell = '''set -eu
umask 077
pgpass=$(mktemp /tmp/sauna-pgpass.XXXXXX)
trap 'rm -f "$pgpass"' EXIT
printf '127.0.0.1:5432:sauna_local:sauna_admin:%s\\n' "$(cat /run/sauna-secrets/postgres-admin-password)" > "$pgpass"
export PGPASSFILE="$pgpass"
exec_psql() { /usr/lib/postgresql/18/bin/psql --no-password --host=127.0.0.1 --port=5432 --username=sauna_admin --dbname=sauna_local --no-psqlrc --tuples-only --no-align --set=ON_ERROR_STOP=1; }
exec_psql
'''
    return command(['container', 'exec', '--user', '0', '--interactive', NAME, '/bin/sh', '-c', shell], sql)


def configure_role():
    verify_directory()
    password = verify_file(DIRECTORY / FILES['app'])
    present = query("SELECT count(*) FROM pg_roles WHERE rolname='sauna_app';")
    if present.strip() == '0':
        # Secret is SQL stdin only; discard raw errors and disable statement logging.
        query("SET log_statement='none'; SET log_min_error_statement='panic';\nCREATE ROLE sauna_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD '" + password + "';\nGRANT CONNECT ON DATABASE sauna_local TO sauna_app;\n")
    elif present.strip() != '1':
        raise RuntimeError('Unexpected local role state')
    safe = query("SELECT count(*) FROM pg_roles WHERE rolname='sauna_app' AND rolcanlogin AND NOT rolsuper AND NOT rolcreatedb AND NOT rolcreaterole AND NOT rolreplication AND NOT rolbypassrls;")
    if safe.strip() != '1':
        raise RuntimeError('Existing local app role has unexpected privileges')
    print('Restricted sauna_app role is configured; existing role passwords are not reset')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['setup', 'start', 'configure-role', 'status', 'stop'])
    args = parser.parse_args()
    if args.action == 'setup':
        setup()
    elif args.action == 'start':
        start()
    elif args.action == 'configure-role':
        configure_role()
    elif args.action == 'status':
        item = owned()
        print(json.dumps({'name': NAME, 'state': item['status']['state'], 'endpoint': '127.0.0.1:55432', 'credentials': 'private files'}))
    elif args.action == 'stop':
        owned()
        command(['container', 'stop', '--signal', 'SIGTERM', '--time', '10', NAME])
        print('Local PostgreSQL stopped; volume and credential files retained')


if __name__ == '__main__':
    try:
        main()
    except (RuntimeError, OSError, ValueError):
        raise SystemExit('Local PostgreSQL action failed. Credentials are never included in diagnostics.') from None
