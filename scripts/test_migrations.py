import shutil
import subprocess
import tempfile
from pathlib import Path
import unittest
from unittest.mock import patch

import local_migrations as migrations
import local_postgres as db


class MigrationPolicyTests(unittest.TestCase):
    def run_guard(self, sql, old=None, filename='20261101010000_example.sql'):
        with tempfile.TemporaryDirectory() as temporary:
            directory = Path(temporary)
            (directory / filename).write_text(sql)
            listed = '' if old is None else 'db/migrations/' + filename + '\n'
            effects = [listed] if old is None else [listed, old.encode()]
            with patch.object(migrations.subprocess, 'check_output', side_effect=effects):
                return migrations.guard(directory=directory)

    def test_additive_ddl_and_misleading_string_literal(self):
        self.assertEqual(self.run_guard("CREATE TABLE example (id uuid PRIMARY KEY, value text DEFAULT 'DROP TABLE'); CREATE INDEX example_value ON example(value);"), 1)

    def test_destructive_and_unknown_sql_fail_closed(self):
        for sql in ['DROP /* obfuscated */ TABLE example', 'TRUNCATE example',
                    'DELETE FROM example', 'ALTER TABLE example DROP COLUMN value',
                    "CREATE FUNCTION dangerous() RETURNS int LANGUAGE sql AS 'SELECT 1'",
                    'DO $$ BEGIN EXECUTE \'DROP TABLE example\'; END $$',
                    'CREATE TABLE safe(id int); DROP TABLE safe']:
            with self.subTest(sql=sql), self.assertRaises(RuntimeError):
                self.run_guard(sql)

    def test_invalid_sql_fails_closed(self):
        with self.assertRaises(RuntimeError):
            self.run_guard('this is not valid SQL;')

    def test_rewritten_history_rejected_independently_of_checksum(self):
        # atlas.sum can be regenerated by an editor; Git baseline bytes cannot be
        # substituted by that checksum, even when both versions are additive SQL.
        with self.assertRaisesRegex(RuntimeError, 'modified or removed'):
            self.run_guard('CREATE TABLE example(id int, extra text);', old='CREATE TABLE example(id int);')

    def test_unchanged_committed_migration_accepted(self):
        sql = 'CREATE TABLE example(id int);'
        self.assertEqual(self.run_guard(sql, old=sql), 1)

    def test_removed_history_and_backdated_new_file_rejected(self):
        with tempfile.TemporaryDirectory() as temporary:
            directory = Path(temporary)
            old_name = '20261102000000_old.sql'
            sql = b'CREATE TABLE old(id int);'
            with patch.object(migrations.subprocess, 'check_output', side_effect=['db/migrations/' + old_name + '\n', sql]):
                with self.assertRaises(RuntimeError):
                    migrations.guard(directory=directory)
            (directory / old_name).write_bytes(sql)
            (directory / '20261101000000_earlier.sql').write_text('CREATE TABLE earlier(id int);')
            with patch.object(migrations.subprocess, 'check_output', side_effect=['db/migrations/' + old_name + '\n', sql]):
                with self.assertRaisesRegex(RuntimeError, 'follow'):
                    migrations.guard(directory=directory)

    def test_foreign_scratch_database_never_reset(self):
        with patch.object(db, 'owned'), patch.object(db, 'query', return_value='someone_else|') as query:
            with self.assertRaisesRegex(RuntimeError, 'unowned'):
                migrations.reset_replay()
            self.assertEqual(query.call_count, 1)
            self.assertNotIn('DROP', query.call_args.args[0])

    def test_database_and_role_rejected_before_execution(self):
        with patch.object(db, 'command') as command:
            for kwargs in [{'database': 'production'}, {'role': 'root'}, {'database': 'sauna_local;DROP DATABASE other'}]:
                with self.assertRaises(RuntimeError):
                    db.query('SELECT 1', **kwargs)
            command.assert_not_called()

    def test_password_file_shell_keeps_pgpassfile_name(self):
        with patch.object(db, 'owned'), patch.object(db, 'command', return_value='1') as command:
            db.query('SELECT 1', database='sauna_atlas_replay', role='app')
            args, stdin = command.call_args.args
            shell = args[-1]
            self.assertIn('export PGPASSFILE="$pgpass"', shell)
            self.assertIn('/run/sauna-secrets/postgres-app-password', shell)
            self.assertIn('--dbname=sauna_atlas_replay', shell)
            self.assertIn('--username=sauna_app', shell)
            self.assertEqual(stdin, 'SELECT 1')

    @unittest.skipUnless(migrations.ATLAS.is_file(), 'Workspace Atlas binary required for checksum tamper integration')
    def test_real_checksum_rehash_does_not_bypass_trusted_git(self):
        with tempfile.TemporaryDirectory(prefix='sauna-migration-guard-') as temporary:
            root = Path(temporary)
            directory = root / 'db/migrations'
            shutil.copytree(migrations.MIGRATIONS, directory)
            for args in [['init', '--quiet'], ['add', 'db/migrations'],
                         ['-c', 'user.name=Local Test', '-c', 'user.email=local@example.invalid', 'commit', '--quiet', '-m', 'Synthetic migration baseline']]:
                subprocess.run(['git', *args], cwd=root, check=True, capture_output=True)
            path = next(directory.glob('*.sql'))
            path.write_text(path.read_text() + '\n-- simulated historical rewrite\n')
            for action in ['hash', 'validate']:
                subprocess.run([str(migrations.ATLAS), 'migrate', action, '--dir', directory.as_uri()], check=True, capture_output=True)
            with patch.object(migrations, 'ROOT', root):
                with self.assertRaisesRegex(RuntimeError, 'modified or removed'):
                    migrations.guard(directory=directory)


if __name__ == '__main__':
    unittest.main()
